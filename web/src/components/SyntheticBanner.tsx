import { isSynthetic } from "../lib/data";
import type { Manifest } from "../lib/contract";

/**
 * Permanent warning when the loaded dataset is SYNTHETIC (rule 1: synthetic data is never presented as real).
 * Renders nothing for REAL data.
 */
export function SyntheticBanner({ manifest }: { manifest: Pick<Manifest, "data_status"> }) {
  if (!isSynthetic(manifest)) return null;
  return (
    <div role="alert" className="synthetic-banner" data-testid="synthetic-banner">
      <strong>SYNTHETIC DATA</strong> — development dataset generated by formulas. It is not real science and must not be
      used to compare real landing sites.
    </div>
  );
}
